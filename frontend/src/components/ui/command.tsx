import * as React from "react";
import { Command as CommandPrimitive } from "cmdk";
import { Search } from "lucide-react";

import { cn } from "@/lib/utils";

/**
 * cmdk wrapper, styled to match the other hand-written primitives.
 *
 * cmdk brings the parts a palette needs to be usable rather than decorative:
 * fuzzy filtering, arrow-key navigation, `aria-activedescendant` wiring and
 * scroll-into-view for the highlighted row.
 */
export const Command = React.forwardRef<
  React.ElementRef<typeof CommandPrimitive>,
  React.ComponentPropsWithoutRef<typeof CommandPrimitive>
>(({ className, ...props }, ref) => (
  <CommandPrimitive ref={ref} className={cn("flex h-full w-full flex-col", className)} {...props} />
));
Command.displayName = "Command";

